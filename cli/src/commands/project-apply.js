import fs from 'node:fs';
import path from 'node:path';
import { expandPath, runGit } from '../projects.js';
import { layoutOf, RULER_TOML } from '../layout.js';
import { unitInfo, rootNestedOn, nestedOffTodo } from '../unit.js';
import { openProject, revisionLabel } from './project-update.js';
import { composeUnit, writeComposedOrFail, rulerStep, report, defaultRunRuler } from './sync-common.js';
import { t } from '../i18n.js';

const STRAY = 'CLAUDE.md';
/** ruler 가 만든 파일의 표시: 맨 앞의 생성 주석, 또는 규칙 파일마다 붙이는 출처 줄. */
const rulerMade = text => text.startsWith('<!-- Generated by Ruler -->') || /^<!-- Source: .+ -->\r?$/m.test(text);

/**
 * 조합 결과가 없을 때(.ruler/ruler.toml 이 없을 때) ruler 가 모든 에이전트로 돌아 만든 CLAUDE.md. Claude Code 는 그것만 읽어
 * AGENTS.md 를 가린다. ruler 표시가 있으면 지울 목록에 넣고, 없으면 사용자 파일일 수 있어 두고 알린다.
 */
function strayRulerOutput(project, files, todos) {
  let text;
  try {
    text = fs.readFileSync(path.join(project, STRAY), 'utf8');
  } catch {
    return;
  }
  if (rulerMade(text)) {
    files[STRAY] = null;
    todos.push({ kind: 'stray-ruler-output', item: null, message: t('todo.strayRulerRemoved', { file: STRAY }) });
  } else {
    todos.push({ kind: 'stray-ruler-output', item: null, message: t('todo.strayRulerKept', { file: STRAY }) });
  }
}

/**
 * 서버 없이 .guideline/ 에서 생성물을 조합해 쓰고 git 루트에서 ruler 를 돈다. 클론·새 워크트리 직후, prepare 에서 쓴다.
 * dir(단위 디렉터리)를 주지 않으면 --project, 그것도 없으면 cwd. 0 완료, 1 쓰기 실패, 2 받은 적 없음·이전 전 배치·단위 문제.
 * @returns {Promise<number>}
 */
export async function projectApply({
  dir: given, project, json = false, env = process.env, out = console.log, err = console.error, cwd = process.cwd(), runRuler = defaultRunRuler, git = runGit,
}) {
  const dir = given ?? (project !== undefined ? expandPath(project) : cwd);
  const opened = openProject({ dir, err });
  if (opened.code !== undefined) return opened.code;
  const { manifest, lock } = opened;
  const layout = layoutOf(lock, dir);
  if (layout === 'ruler') {
    err(t('apply.needsUpdate'));
    return 2;
  }
  if (layout === 'none') {
    err(t('update.notYet'));
    return 2;
  }

  const unit = unitInfo(dir, git);
  const hadToml = fs.existsSync(path.join(dir, ...RULER_TOML.split('/')));
  const composed = composeUnit({ project: dir, nested: unit.nested, manifest });
  const files = { ...composed.files };
  const todos = [...composed.todos];
  if (!hadToml) strayRulerOutput(dir, files, todos);
  const w = writeComposedOrFail(dir, files, err);
  if (w.failed) return 1;
  if (unit.nested && !rootNestedOn(unit.root)) todos.push(nestedOffTodo(unit.root));
  // apply 는 ruler apply 를 대신하므로 바뀐 것이 없어도 ruler 를 돈다(에이전트 파일만 지워진 경우).
  rulerStep({ root: unit.root, env, runRuler, todos });
  report({ result: { revision: revisionLabel(lock.revisions), written: w.written, deleted: w.deleted, todos }, json, out });
  return 0;
}
